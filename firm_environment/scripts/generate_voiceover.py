"""
Генерация озвучки диктора нейросетью edge-tts (ru-RU-DmitryNeural)
"""

import asyncio
import edge_tts
from pathlib import Path

VOICE_TEXT = """
В микроструктуре современного крипторынка доли секунды решают всё. Миллионы ордеров, скрытые роботы и хаос биржевого стакана. Традиционные индикаторы опаздывают. Пришло время локального машинного интеллекта.

Встречайте промышленный комплекс Antigravity 2.5. Два специализированных локальных разума в едином контуре: легковесный Qwen круглосуточно сканирует стакан и выявляет спуфинг и айсберги, а стратегический мозг DeepSeek-R1 рассчитывает математическое преимущество и цепочки рассуждений.

Математика Авелланеды-Стойкова и анализ дисбаланса стакана OBI. Вход строго из защищенной зоны Z2 аномальных свечей, стоп-лосс за плотностями крупных институциональных игроков и трехступенчатый вывод прибыли в безубыток.

Никаких эмоций и тильта. Жесткий лимит риска — три процента капитала, аппаратный стоп двадцать пять базисных пунктов и автономный контур самоисцеления Actor-Critic, устраняющий ошибки на лету.

Antigravity. Полная автономность. Локальная мощность. Новая эра высокочастотного криптотрейдинга.
""".strip()

async def generate():
    voice = "ru-RU-DmitryNeural"
    output_file = "firm_environment/storage/voiceover.mp3"
    communicate = edge_tts.Communicate(VOICE_TEXT, voice, rate="+0%", pitch="-2Hz")
    await communicate.save(output_file)
    print("Озвучка успешно сгенерирована:", output_file)

if __name__ == "__main__":
    asyncio.run(generate())
